"""Offline tests for printer presets and /slice's preset resolution.

No slicer, no network, no real ~/.printpal — every test isolates the DB by
monkeypatching db.DB_PATH to a temp file. The /slice backend-selection and
preset-resolution are exercised with stub tool objects whose forward() writes a
G-code file (so the DB insert path runs for real), capturing the kwargs.
"""

from __future__ import annotations

import pytest

from printpal import db
from printpal.commands import thing as pp_thing
from printpal.config import ORCA_DEFAULTS


@pytest.fixture()
def tmp_db(tmp_path, monkeypatch):
    """Fresh, isolated PrintPal DB for each test."""
    monkeypatch.setattr(db, "DB_PATH", tmp_path / "printpal.db")
    db.init_db()
    return tmp_path / "printpal.db"


def _seed_model(model_bytes: bytes = b"\x00" * 128):
    return db.insert_thing(
        thingiverse_id=None,
        name="m.stl",
        creator=None,
        license=None,
        url=None,
        file_name="m.stl",
        file_size=len(model_bytes),
        file_data=model_bytes,
        file_type="model",
        status="downloaded",
    )


class _StubOrcaTool:
    """Stands in for orca_slice_model: records kwargs, writes a gcode file."""

    name = "orca_slice_model"

    def __init__(self):
        self.kwargs = None

    def forward(self, **kwargs):
        self.kwargs = kwargs
        from pathlib import Path

        Path(kwargs["output_path"]).write_bytes(b"; generated by OrcaSlicer\nG1 X0\n")
        return {
            "gcode_path": kwargs["output_path"],
            "gcode_size_bytes": 40,
            "settings": {
                "machine": kwargs["machine"],
                "process": kwargs["process"],
                "filament": kwargs["filament"],
            },
            "stats": {},
        }


class _StubCuraTool:
    name = "cura_slice_model"

    def __init__(self):
        self.kwargs = None

    def forward(self, **kwargs):
        self.kwargs = kwargs
        from pathlib import Path

        Path(kwargs["output_path"]).write_bytes(b"; Cura G-code\n")
        return {
            "gcode_path": kwargs["output_path"],
            "gcode_size_bytes": 20,
            "printer": kwargs.get("printer", "?"),
            "settings": {},
            "stats": {},
        }


def _gcode_things():
    return [t for t in db.list_things() if t["file_type"] == "gcode"]


