def test_slice_auto_prefers_orca(tmp_db):
    pp_thing.cmd_slice([str(_seed_model())], [_StubOrcaTool(), _StubCuraTool()])
    g = _gcode_things()
    assert g, "expected a gcode thing"
    src = db.get_thing(g[0]["id"])
    assert src is not None
    assert bytes(src["file_data"]).startswith(b"; generated by OrcaSlicer")


def test_slice_orca_uses_active_printer_presets(tmp_db):
    db.upsert_printer(
        "v24",
        orca_machine="Voron 2.4 0.4 nozzle",
        orca_process="Voron Process",
        orca_filament="Voron PLA",
    )
    db.use_printer("v24")

    tool = _StubOrcaTool()
    pp_thing.cmd_slice([str(_seed_model())], [tool])

    assert tool.kwargs is not None
    assert tool.kwargs["machine"] == "Voron 2.4 0.4 nozzle"
    assert tool.kwargs["process"] == "Voron Process"
    assert tool.kwargs["filament"] == "Voron PLA"
    # absolute extrusion default is injected
    assert tool.kwargs["overrides"]["use_relative_e_distances"] == 0


def test_slice_orca_falls_back_to_config_then_defaults(tmp_db, monkeypatch):
    # No active printer, but a config override set -> config wins over defaults.
    db.set_setting("orca_machine", "Config Machine")
    tool = _StubOrcaTool()
    pp_thing.cmd_slice([str(_seed_model())], [tool])
    assert tool.kwargs is not None
    assert tool.kwargs["machine"] == "Config Machine"

    # Fresh DB + no config: defaults win.
    db.delete_setting("orca_machine")
    tool2 = _StubOrcaTool()
    pp_thing.cmd_slice([str(_seed_model(b"\x01" * 128))], [tool2])
    assert tool2.kwargs is not None
    assert tool2.kwargs["machine"] == ORCA_DEFAULTS["orca_machine"]


def test_slice_force_cura_uses_active_printer_cura_id(tmp_db):
    db.upsert_printer("v24", cura_printer="voron24_cura")
    db.use_printer("v24")
    tool = _StubCuraTool()
    pp_thing.cmd_slice([str(_seed_model()), "--slicer", "cura"], [tool])
    assert tool.kwargs is not None
    assert tool.kwargs["printer"] == "voron24_cura"


def test_slice_cura_flag_beats_active_printer(tmp_db):
    db.upsert_printer("v24", cura_printer="voron24_cura")
    db.use_printer("v24")
    tool = _StubCuraTool()
    pp_thing.cmd_slice([str(_seed_model()), "--slicer", "cura", "--printer", "prusa_mk4"], [tool])
    assert tool.kwargs is not None
    assert tool.kwargs["printer"] == "prusa_mk4"  # explicit flag wins


# --------------------------------------------------------------------------- #
# Adhesion mapping: the unified keyword must translate to Orca's real settings
# (brim_width / raft_layers / skirt_loops), NOT a nonexistent "adhesion_type".
# --------------------------------------------------------------------------- #
def _orca_overrides_for(args):
    tool = _StubOrcaTool()
    pp_thing.cmd_slice([str(_seed_model()), "--slicer", "orca"] + args, [tool])
    assert tool.kwargs is not None
    return tool.kwargs["overrides"]


def test_orca_adhesion_brim(tmp_db):
    ov = _orca_overrides_for(["--adhesion", "brim"])
    assert ov["brim_width"] == "5"
    assert ov["skirt_loops"] == "0"
    assert "adhesion_type" not in ov  # must not leak the Cura keyword
    assert ov["use_relative_e_distances"] == 0  # still injected


def test_orca_adhesion_raft(tmp_db):
    ov = _orca_overrides_for(["--adhesion", "raft"])
    assert ov["raft_layers"] == "3"
    assert ov["skirt_loops"] == "0"
    assert ov["brim_width"] == "0"


def test_orca_adhesion_none(tmp_db):
    ov = _orca_overrides_for(["--adhesion", "none"])
    assert ov["skirt_loops"] == "0"
    assert ov["brim_width"] == "0"
    assert ov["raft_layers"] == "0"


def test_orca_infill_percent_and_supports(tmp_db):
    ov = _orca_overrides_for(["--infill", "40", "--supports"])
    assert ov["sparse_infill_density"] == "40%"  # % suffix
    assert ov["enable_support"] is True
