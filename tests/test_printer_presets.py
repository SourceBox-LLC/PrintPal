def test_default_printer_seeded(tmp_db):
    names = {p["name"] for p in db.list_printers()}
    assert "ender-3-pro" in names
    e3 = db.get_printer("ender-3-pro")
    assert e3 is not None
    assert e3["cura_printer"] == "creality_ender3pro"
    assert e3["orca_machine"] == ORCA_DEFAULTS["orca_machine"]


def test_upsert_and_get_case_insensitive(tmp_db):
    db.upsert_printer("Voron 2.4", cura_printer="voron24", orca_machine="Voron 2.4 0.4 nozzle")
    p = db.get_printer("voron 2.4")
    assert p is not None
    assert p["name"] == "Voron 2.4"
    assert p["cura_printer"] == "voron24"


def test_upsert_overwrites_existing(tmp_db):
    db.upsert_printer("x", orca_machine="M1")
    db.upsert_printer("X", orca_machine="M2")  # case-insensitive unique
    p = db.get_printer("x")
    assert p is not None and p["orca_machine"] == "M2"
    assert len([q for q in db.list_printers() if q["name"].lower() == "x"]) == 1


def test_delete_printer(tmp_db):
    db.upsert_printer("gone")
    assert db.delete_printer("gone") is True
    assert db.get_printer("gone") is None
    assert db.delete_printer("gone") is False


def test_use_printer_writes_settings_and_active(tmp_db):
    db.upsert_printer(
        "myprinter",
        cura_printer="my_cura",
        orca_machine="My Machine",
        orca_process="My Process",
        orca_filament="My PLA",
    )
    applied = db.use_printer("myprinter")
    assert applied is not None
    assert db.get_setting("cura_printer") == "my_cura"
    assert db.get_setting("orca_machine") == "My Machine"
    assert db.get_setting("orca_process") == "My Process"
    assert db.get_setting("orca_filament") == "My PLA"
    active = db.get_active_printer()
    assert active is not None and active["name"] == "myprinter"


def test_use_printer_unknown_returns_none(tmp_db):
    assert db.use_printer("nope") is None
    assert db.get_active_printer() is None


def test_remove_active_printer_clears_applied_settings(tmp_db, monkeypatch):
    """Removing the active printer must clear the settings it applied so /slice
    doesn't keep using a deleted printer's presets."""
    from printpal.commands import printer as pp_printer

    monkeypatch.setattr(pp_printer, "prompt_yes_no", lambda _msg: True)
    db.upsert_printer(
        "v24", orca_machine="Voron", orca_process="P", orca_filament="F", cura_printer="voron24"
    )
    db.use_printer("v24")
    assert db.get_setting("orca_machine") == "Voron"

    pp_printer.cmd_printer(["remove", "v24"])
    assert db.get_active_printer() is None
    assert db.get_setting("orca_machine") is None  # cleared, not left dangling


